// Bundles src/ into the single self-contained script shipped in the skill (and used as the npm bin).
import fs from "node:fs";
import path from "node:path";
import { build } from "esbuild";

const pkg = JSON.parse(fs.readFileSync(new URL("../package.json", import.meta.url), "utf8"));
const outfile = new URL("../plugin/skills/codex/scripts/codex-run.mjs", import.meta.url).pathname;

const result = await build({
  entryPoints: [new URL("../src/cli.mjs", import.meta.url).pathname],
  outfile,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  legalComments: "eof",
  metafile: true,
  define: { __CODEX_RUN_VERSION__: JSON.stringify(pkg.version) },
  // ws optionally requires native addons; without them it falls back to pure JS
  external: ["bufferutil", "utf-8-validate"],
  banner: {
    js: "#!/usr/bin/env node\n// Generated by scripts/build.mjs from src/ — do not edit; see https://github.com/kcng0/cc-codex-run\n" +
      "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);",
  },
});
fs.chmodSync(outfile, 0o755);

// Licenses of every npm package that ended up in the bundle (MIT/BSD require shipping their notices)
const root = new URL("..", import.meta.url).pathname;
const pkgDirs = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const m = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
  if (m) pkgDirs.add(m[1]);
}
const sections = [...pkgDirs].sort().map((dir) => {
  const meta = JSON.parse(fs.readFileSync(path.join(root, dir, "package.json"), "utf8"));
  const file = fs.readdirSync(path.join(root, dir)).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  if (!file) throw new Error(`${meta.name}: no license file to ship`);
  const text = fs.readFileSync(path.join(root, dir, file), "utf8").trim();
  return `## ${meta.name} ${meta.version} (${meta.license})\n\n${text}\n`;
});
fs.writeFileSync(path.join(path.dirname(outfile), "THIRD_PARTY_LICENSES.md"),
  `# Third-party licenses\n\n\`codex-run.mjs\` bundles the following packages.\n\n${sections.join("\n")}`);

// The plugin manifest carries the same version so plugin installs update when the package does
const manifest = new URL("../plugin/.claude-plugin/plugin.json", import.meta.url);
const plugin = JSON.parse(fs.readFileSync(manifest, "utf8"));
if (plugin.version !== pkg.version) {
  plugin.version = pkg.version;
  fs.writeFileSync(manifest, JSON.stringify(plugin, null, 2) + "\n");
}
console.log(`built ${outfile}`);
